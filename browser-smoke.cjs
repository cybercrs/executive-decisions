const errors = [];
function track(page) {
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
}
async function choose(page, answers) {
  for (let j = 0; j < answers.length; j++) {
    const radios = page.locator('fieldset.question').nth(j).getByRole('radio');
    if (typeof answers[j] === 'number') await radios.nth(answers[j]).check();
    else await page.locator('fieldset.question').nth(j).getByRole('radio', { name: answers[j], exact: true }).check();
  }
  await page.getByRole('button', { name: 'Check answers', exact: true }).click();
}
async function chooseStatements(page, selected) {
  const boxes = page.getByRole('checkbox');
  assert.equal(await boxes.count(), 6);
  for (let i = 0; i < 6; i++) await boxes.nth(i).setChecked(selected.includes(i));
  await page.getByRole('button', { name: 'Check answers', exact: true }).click();
}
